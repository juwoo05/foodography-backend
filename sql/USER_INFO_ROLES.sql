-- USER_INFO 권한 컬럼 추가 (콤마 구분, 예: "ROLE_USER,ROLE_ADMIN")
-- 기존·신규 회원은 기본값 ROLE_USER
ALTER TABLE USER_INFO
    ADD COLUMN ROLES VARCHAR(100) NOT NULL DEFAULT 'ROLE_USER';

-- 관리자 지정 — EMAIL 은 AES128-CBC 암호문으로 저장됨
-- 'LOy10BZsD2XmBTFrmxsF0R8BDMF8+rUDpcZRF3weZK0=' = EncryptUtil.encAES128CBC("jijuwoo@gmail.com")
UPDATE USER_INFO
   SET ROLES = 'ROLE_USER,ROLE_ADMIN'
 WHERE EMAIL = 'LOy10BZsD2XmBTFrmxsF0R8BDMF8+rUDpcZRF3weZK0=';

-- 확인
SELECT USER_ID, USER_NAME, ROLES FROM USER_INFO WHERE ROLES LIKE '%ROLE_ADMIN%';
